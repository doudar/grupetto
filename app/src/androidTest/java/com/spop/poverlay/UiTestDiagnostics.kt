package com.spop.poverlay

import android.graphics.Rect
import android.os.Build
import android.os.ParcelFileDescriptor
import android.view.View
import android.view.ViewGroup
import android.view.WindowManager
import android.view.inspector.WindowInspector
import androidx.compose.ui.test.isRoot
import androidx.compose.ui.test.printToString
import androidx.compose.ui.test.junit4.ComposeContentTestRule
import androidx.test.platform.app.InstrumentationRegistry
import org.junit.rules.TestWatcher
import org.junit.runner.Description
import java.io.File

/** Opt-in fixture diagnostics, captured before Compose disposes the test window.
 * Shell-owned output survives connected-test APK cleanup; no assertion is changed.
 */
internal class UiTestDiagnostics(private val compose: ComposeContentTestRule) : TestWatcher() {
    override fun failed(error: Throwable, description: Description) = capture(description, "failed", error)
    override fun succeeded(description: Description) {
        if (InstrumentationRegistry.getArguments().getString("uiDiagnosticsPassed") == "true") {
            capture(description, "passed", null)
        }
    }

    private fun capture(description: Description, outcome: String, failure: Throwable?) {
        if (InstrumentationRegistry.getArguments().getString("uiDiagnostics") != "true") return
        runCatching {
            val instrumentation = InstrumentationRegistry.getInstrumentation()
            val context = instrumentation.targetContext
            val name = "${description.className.substringAfterLast('.')}.${description.methodName}-$outcome"
                .replace(Regex("[^A-Za-z0-9_.-]"), "_")
            val report = StringBuilder().appendLine(description.displayName).appendLine(failure?.stackTraceToString() ?: "Passed")
            fun section(title: String, value: () -> String) {
                report.appendLine("\n=== $title ===")
                report.appendLine(runCatching(value).getOrElse { "Diagnostic unavailable: $it" })
            }
            section("Display configuration") {
                val metrics = android.util.DisplayMetrics()
                @Suppress("DEPRECATION")
                (context.getSystemService(android.content.Context.WINDOW_SERVICE) as WindowManager)
                    .defaultDisplay.getRealMetrics(metrics)
                "Physical: $metrics\nResources: ${context.resources.displayMetrics}\nConfiguration: ${context.resources.configuration}\n" +
                    "Heap: max=${Runtime.getRuntime().maxMemory()}, free=${Runtime.getRuntime().freeMemory()}"
            }
            section("Native windows") {
                var windows = "WindowInspector requires API29"
                if (Build.VERSION.SDK_INT >= 29) instrumentation.runOnMainSync {
                    windows = buildString {
                        WindowInspector.getGlobalWindowViews().forEach { root ->
                            var remaining = 80
                            fun visit(view: View, depth: Int) {
                                if (remaining-- <= 0 || depth > 8) return
                                val location = IntArray(2).also(view::getLocationOnScreen)
                                val visible = Rect()
                                val shown = view.getGlobalVisibleRect(visible)
                                appendLine("${"  ".repeat(depth)}${view.javaClass.name}: ${view.width}x${view.height}; " +
                                    "screen=${location.contentToString()}; visible=$shown/$visible; " +
                                    "focus=${view.hasWindowFocus()}; layout=${view.layoutParams}")
                                if (view is ViewGroup) for (index in 0 until view.childCount) visit(view.getChildAt(index), depth + 1)
                            }
                            visit(root, 0)
                        }
                    }
                }
                windows
            }
            section("Compose semantics") {
                compose.onAllNodes(isRoot(), useUnmergedTree = true).printToString(maxDepth = 30).take(300_000)
            }
            val directory = File(checkNotNull(context.getExternalFilesDir(null)), "ui-fixture-diagnostics")
            check(directory.isDirectory || directory.mkdirs())
            val file = File(directory, "$name.txt").apply { writeText(report.toString()) }
            val label = (InstrumentationRegistry.getArguments().getString("uiDiagnosticsLabel") ?: "suite")
                .replace(Regex("[^A-Za-z0-9_.-]"), "_")
            val root = "/data/local/tmp/grupetto-ui-test-diagnostics/$label"
            // executeShellCommand does not interpret shell operators or quoted compound commands.
            // These paths are generated by Android or sanitized above and contain no spaces.
            for (command in listOf("mkdir -p $root", "screencap -p $root/$name.png",
                "cp ${file.absolutePath} $root/$name.txt")) {
                ParcelFileDescriptor.AutoCloseInputStream(instrumentation.uiAutomation.executeShellCommand(command))
                    .bufferedReader().use { it.readText() }
            }
        }.onFailure { android.util.Log.e("UiTestDiagnostics", "Could not preserve fixture diagnostics", it) }
    }
}
